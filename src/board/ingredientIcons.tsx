/** Icons drawn upright that look better tilted (degrees). */
const TILT: Partial<Record<IngredientId, number>> = { limone: -30 };

/** An ingredient icon, drawn in the current text colour; `style` sets its size, place and colour. */
export function IngredientIcon({ id, style, className = '' }: { id: IngredientId; style?: CSSProperties; className?: string }) {
  return (
    <svg
      className={`ingredient ${className}`}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.6}
      strokeLinecap="round"
      strokeLinejoin="round"
      style={style}
      aria-hidden="true"
    >
      <g transform={TILT[id] ? `rotate(${TILT[id]} 12 12)` : undefined}>
        {SHAPES[id].map((s, i) =>
          typeof s === 'string' ? <path key={i} d={s} /> : <path key={i} d={s.fill} fill="currentColor" stroke="none" />,
        )}
      </g>
    </svg>
  );
}
